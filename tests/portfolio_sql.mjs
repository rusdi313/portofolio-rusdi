import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../.verification/node_modules/@electric-sql/pglite/dist/index.js';

const read = async name => (await readFile(new URL(`../supabase/${name}`, import.meta.url), 'utf8')).replace(/^\uFEFF/, '');
for (const arrayType of ['text[]', 'jsonb']) {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated;
    grant usage on schema public to anon, authenticated;
    create publication supabase_realtime;
    create schema storage;
    create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
    create table public.projects(id bigint generated by default as identity primary key, created_at timestamptz default now(), "Title" text not null, "Description" text, "Img" text not null, "Link" text, "Github" text, "Features" ${arrayType}, "TechStack" ${arrayType});
    create table public.certificates(id bigint generated by default as identity primary key, created_at timestamptz default now(), "Img" text not null);
    insert into public.projects(id, "Title", "Description", "Img") values (4, 'Existing project', 'Preserve me', 'https://example.com/old.png');
    insert into public.certificates("Img") values ('https://example.com/old-cert.png');
  `);
  const schema = await read('portfolio-schema.sql');
  const experiences = await read('seed-experiences.sql');
  const seed = await read('portfolio-seed.sql');
  await db.exec(schema);
  await db.exec(experiences);
  // Reproduce the reported collision: the next automatic ID is already occupied.
  await db.exec("select setval(pg_get_serial_sequence('public.projects','id'), 4, false)");
  await db.exec(seed);
  assert.deepEqual((await db.query('select id from projects order by id')).rows.map(row => Number(row.id)), [4, 5, 6, 7]);
  // An already advanced sequence must never move backwards on rerun.
  await db.exec("select setval(pg_get_serial_sequence('public.projects','id'), 100, true)");
  await db.exec(schema);
  await db.exec(experiences);
  await db.exec(seed);
  assert.ok(Number((await db.query("select nextval(pg_get_serial_sequence('public.projects','id')) as id")).rows[0].id) > 100);
  const count = async table => Number((await db.query(`select count(*) as count from public.${table}`)).rows[0].count);
  assert.equal(await count('profile'), 1);
  assert.equal(await count('skills'), 37);
  assert.equal(await count('education'), 2);
  assert.equal(await count('projects'), 4);
  assert.equal(await count('certificates'), 1);
  assert.equal((await db.query('select "Img" from certificates')).rows[0].Img, 'https://example.com/old-cert.png');
  assert.equal(await count('experiences'), 5);
  assert.equal((await db.query(`select "Description" from projects where "Title"='Existing project'`)).rows[0].Description, 'Preserve me');
  assert.equal((await db.query(`select period from experiences where id='stukka-frontend'`)).rows[0].period, 'Nov 2025 – Feb 2026 · 4 mos');
  // Subsequent seeds preserve dashboard edits.
  await db.exec(`update profile set headline='Edited profile'; update experiences set role='Edited role' where id='uin-it-support';`);
  await db.exec(seed);
  assert.equal((await db.query('select headline from profile')).rows[0].headline, 'Edited profile');
  assert.equal((await db.query(`select role from experiences where id='uin-it-support'`)).rows[0].role, 'Edited role');
  // A pre-existing permissive policy cannot bypass draft protection after migration.
  await db.exec(`create policy "Legacy broad read" on projects for select to anon using(true);`);
  await db.exec(schema);
  await db.exec(`update projects set is_published=false where "Title"='Existing project';`);
  for (const role of ['anon', 'authenticated']) {
    await db.exec(`set role ${role}`);
    assert.equal(await count('projects'), 3);
    assert.equal((await db.query(`select * from projects where "Title"='Existing project'`)).rows.length, 0);
    await assert.rejects(db.exec(`insert into projects("Title","Img") values('Unauthorized', '')`), /permission denied/i);
    await assert.rejects(db.exec(`update projects set "Title"='Unauthorized'`), /permission denied/i);
    await assert.rejects(db.exec('delete from projects'), /permission denied/i);
    await db.exec('reset role');
  }
  await db.close();
  console.log(`PASS (${arrayType}): repeatable schema/seed, CV counts, existing content, manual edits, published-only RLS and denied public writes.`);
}
