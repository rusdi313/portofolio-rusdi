-- Run in Supabase SQL Editor before deploying the new frontend.
-- Preserves existing content. Read policies are replaced to enforce published-only access.
begin;
create table if not exists public.profile (
  id text primary key default 'main' check (id = 'main'),
  name text not null, headline text not null, status text,
  hero_description text, about text, approach text, location text,
  email text, linkedin_url text, github_url text, cv_url text, photo_url text,
  contact_title text, contact_description text,
  is_published boolean not null default true, sort_order integer not null default 0
);
create table if not exists public.skills (
  id text primary key default gen_random_uuid()::text,
  name text not null, category text not null,
  is_published boolean not null default true, sort_order integer not null default 0
);
create table if not exists public.education (
  id text primary key default gen_random_uuid()::text,
  institution text not null, degree text not null, period text not null, gpa text,
  highlights text[] not null default '{}',
  is_published boolean not null default true, sort_order integer not null default 0
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  "Title" text not null, "Description" text, "Img" text, "Link" text, "Github" text,
  "TechStack" text[] default '{}', "Features" text[] default '{}'
);
alter table public.projects
  add column if not exists category text not null default 'Web Development',
  add column if not exists role text,
  add column if not exists period text,
  add column if not exists context text,
  add column if not exists methods text,
  add column if not exists outcomes text,
  add column if not exists report_url text,
  add column if not exists featured boolean not null default false,
  add column if not exists is_published boolean not null default true,
  add column if not exists sort_order integer not null default 100;
create table if not exists public.certificates (
  id bigint generated by default as identity primary key, "Img" text
);
alter table public.certificates
  add column if not exists name text,
  add column if not exists issuer text,
  add column if not exists issued_on date,
  add column if not exists credential_url text,
  add column if not exists category text,
  add column if not exists featured boolean not null default false,
  add column if not exists is_published boolean not null default true,
  add column if not exists sort_order integer not null default 100;
create table if not exists public.experiences (
  id text primary key default gen_random_uuid()::text,
  role text not null, company text not null, period text not null, location text, type text,
  current boolean not null default false, summary text,
  highlights text[] not null default '{}', technologies text[] not null default '{}',
  sort_order integer not null default 0
);
alter table public.experiences add column if not exists is_published boolean not null default true;

-- Restrict all six content tables to public reads of published rows only.
-- Existing permissive SELECT / ALL policies must not bypass draft filtering.
do $$
declare target text; existing_policy record;
begin
  foreach target in array array['profile','skills','education','projects','certificates','experiences'] loop
    execute format('alter table public.%I enable row level security', target);
    execute format('revoke all on public.%I from anon, authenticated', target);
    execute format('grant select on public.%I to anon, authenticated', target);
    for existing_policy in select policyname from pg_policies
      where schemaname = 'public' and tablename = target and cmd in ('SELECT', 'ALL') loop
      execute format('drop policy %I on public.%I', existing_policy.policyname, target);
    end loop;
    execute format('create policy "Published portfolio content" on public.%I for select to anon, authenticated using (is_published = true)', target);
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = target) then
      execute format('alter publication supabase_realtime add table public.%I', target);
    end if;
  end loop;
end $$;

-- Public portfolio assets; uploads/edits are managed from the dashboard.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('portfolio-assets', 'portfolio-assets', true, 10485760, array['image/jpeg','image/png','image/webp','application/pdf'])
on conflict (id) do nothing;
commit;
